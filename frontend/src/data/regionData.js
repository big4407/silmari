const SIDO_IDS = new Set(REGION_DATA.root.regions.map((r) => r.id));

export function isSidoKey(key) {
  return SIDO_IDS.has(key);
}

export function findGuInSido(sidoId, guLabel) {
  const target = (guLabel || '').replace(/\s/g, '');
  return (
    REGION_DATA[sidoId]?.regions?.find(
      (r) => r.label.replace(/\s/g, '') === target,
    ) || null
  );
}

export function findSidoIdForGu(guKey) {
  for (const sido of REGION_DATA.root.regions) {
    const gu = REGION_DATA[sido.id]?.regions?.find((r) => r.id === guKey);
    if (gu) return { sidoId: sido.id, gu };
  }
  return null;
}
